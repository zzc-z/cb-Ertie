# DB & MODELS ##########################################################################################################
from sqlalchemy.exc import SQLAlchemyError
from app.factory.extensions import database
from app.models.members.members import Role

# EXTENSIONS ###########################################################################################################
from app.factory.extensions.custom.inputValidator import inputValidator


########################################################################################################################
# METHODS ##############################################################################################################
########################################################################################################################
def delete(objectID: int) -> int:
    try:
        inputValidator.positiveInteger(objectID)
        return database.deleteObjectAndHistory(Role, objectID, associatedObjects=['users'])

    except SQLAlchemyError as e:
        raise RuntimeError(f'DB Error @ roleDelete.delete: {e}') from e
    except Exception as e:
        raise RuntimeError(f'Unexpected Error @ roleDelete.delete: {e}') from e
